"""One table of every Pod session: what ran, on what, what it cost, what came out, where the report is.

python3 -I tools/offline/build_sessions_index.py   -> artifacts/reports/sessions-index.json + docs/reports/SESSIONS.md
Reads artifacts/infra_sessions/*/session.json, bundle.json, analysis/session_summary.json (built on demand), the budget
ledger and docs/reports/*.md (a report is linked when it names the session directory).
"""
from __future__ import annotations

import glob
import json
import os
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SESS = ROOT / "artifacts/infra_sessions"


def main() -> None:
    ledger = json.loads((ROOT / "artifacts/p0/budget-ledger.json").read_text())
    cost = {}
    for tier, t in ledger["tiers"].items():
        for s in t.get("sessions", []):
            if "estimate_usd" in s:
                cost[s["session"]] = {"tier": tier, "estimate_usd": s["estimate_usd"], "gpu": s.get("gpu"), "status": s.get("status")}
    reports = {p: open(p, errors="replace").read() for p in glob.glob(str(ROOT / "docs/reports/*.md")) if not p.endswith("SESSIONS.md")}
    night = "docs/reports/2026-11-10-retrospective-and-roadmap.md"  # covers every tier-N1 session (it does not list them by name)
    rows = []
    for sj in sorted(glob.glob(str(SESS / "*/session.json"))):
        sd = Path(sj).parent
        s = json.loads(Path(sj).read_text())
        name = sd.name
        row = {"session": name, "created_utc": s.get("created_utc"), "gpu": (s.get("gpu_type") or "").replace("NVIDIA ", "").replace("GeForce ", ""), "rate": s.get("quoted_gpu_hourly_usd"), "pod_id": s.get("pod_id")}
        row.update({k: v for k, v in cost.get(name, {}).items() if k != "gpu"})
        if (sd / "recovered/out").exists():
            summ = sd / "analysis/session_summary.json"
            if not summ.exists():
                subprocess.run([sys.executable, "-I", str(ROOT / "tools/offline/session_summary.py"), str(sd)], capture_output=True)
            if summ.exists():
                d = json.loads(summ.read_text())
                t = d.get("train", {})
                row.update({"updates": t.get("updates"), "it_per_s": t.get("it_per_s_median"), "host": (d.get("host_info") or "").split(";")[0].replace("model name\t: ", "")[:40]})
                b = d.get("bundle") or {}
                row.update({"config_id": b.get("config_id"), "anchor_obs": b.get("anchor_obs"), "seed": b.get("seed")})
                ok = lambda x: "init" not in x["dir"] and x.get("kind", "ckpt") == "ckpt" and (x.get("protocol_id") or "nominal").find("robust") < 0
                wins = [w for w in d.get("window10s", []) if ok(w)]
                fulls = [f for f in d.get("fullclip", []) if ok(f) and (f.get("data_label") or "").find("context") < 0 and (f.get("data_label") or "").find("BONES") < 0]
                swa_w = [w for w in d.get("window10s", []) if w.get("kind") == "swa"]
                swa_f = [f for f in d.get("fullclip", []) if f.get("kind") == "swa"]
                if swa_w:
                    row.update({"swa_win": f"{swa_w[-1]['completed']}/{swa_w[-1]['windows']}", "swa_win_macro": round(swa_w[-1]["macro"], 3)})
                if swa_f:
                    row.update({"swa_full": f"{swa_f[-1]['completed']}/{swa_f[-1]['clips']}", "swa_full_macro": round(swa_f[-1]["macro"], 3)})
                if wins:
                    w = wins[-1]
                    row.update({"win_final": f"{w['completed']}/{w['windows']}", "win_macro": round(w["macro"], 3), "anchor_obs_eval": w.get("anchor_obs")})
                if fulls:
                    f = fulls[-1]
                    row.update({"full_final": f"{f['completed']}/{f['clips']}", "full_macro": round(f["macro"], 3)})
        row["reports"] = sorted(os.path.relpath(p, ROOT) for p, txt in reports.items() if name in txt)
        if row.get("tier") == "N1" and night not in row["reports"]:
            row["reports"].append(night)
        rows.append(row)
    rows.sort(key=lambda r: r.get("created_utc") or "")
    out = {"schema_version": 1, "generated_utc": datetime.utcnow().isoformat() + "Z", "sessions": rows,
           "total_estimate_usd": round(sum(r.get("estimate_usd") or 0 for r in rows), 2)}
    (ROOT / "artifacts/reports/sessions-index.json").write_text(json.dumps(out, indent=1, ensure_ascii=False))
    L = ["# Pod sessions (generated, do not edit by hand)", "", f"Generated by `tools/offline/build_sessions_index.py`, {out['generated_utc']}. Costs are estimates (creation to stop × hourly price); total **${out['total_estimate_usd']}**.",
         "", "| Date | Session | GPU | it/s | Updates | Anchor | Window final | Whole clip final | USD | Reports |", "|---|---|---|---:|---:|---|---|---|---:|---|"]
    for r in rows:
        rep = " ".join(f"[{i + 1}]({os.path.relpath(ROOT / p, ROOT / 'docs/reports')})" for i, p in enumerate(r["reports"])) or "—"
        win = f"{r['win_final']} · {r['win_macro']}" if r.get("win_final") else "—"
        full = f"{r['full_final']} · {r['full_macro']}" if r.get("full_final") else "—"
        anc = {True: "yes", False: "no", None: "—"}[r.get("anchor_obs_eval", r.get("anchor_obs"))]
        L.append(f"| {(r.get('created_utc') or '')[:10]} | `{r['session']}` | {r.get('gpu') or '—'} | {r.get('it_per_s') or '—'} | {r.get('updates') or '—'} | {anc} | {win} | {full} | {r.get('estimate_usd', '—')} | {rep} |")
    (ROOT / "docs/reports/SESSIONS.md").write_text("\n".join(L) + "\n")
    print(f"{len(rows)} sessions, total {out['total_estimate_usd']} USD")


if __name__ == "__main__":
    main()
